//! The languages offered and where their dictionaries come from.
//!
//! Each dictionary = one install unit of two files (`index.aff` + `index.dic`) from `wooorm/dictionaries` at a pinned
//! commit (UTF-8 conversions of the `LibreOffice` dictionaries). Size + SHA-256 of every file are pinned here and checked
//! when it arrives (core `downloads`) and again when it is loaded. Nothing is bundled: each dictionary has its own
//! license (`license`, SPDX expression of the source package), and a download is the person's own act.

use permark_core::downloads::{Asset, Source, Unit};

/// Commit of `wooorm/dictionaries` the files are pinned at.
pub const COMMIT: &str = "8cfea406b505e4d7df52d5a19bce525df98c54ab";

/// Raw files of GitHub; a redirect to any other host is refused.
pub const SOURCE: Source = Source::new(
    "wooorm-dictionaries",
    "https://raw.githubusercontent.com",
    &["raw.githubusercontent.com"],
);

/// Store names of the two files of a dictionary.
pub const AFF: &str = "index.aff";
pub const DIC: &str = "index.dic";

/// What one official file must be.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pin {
    pub bytes: u64,
    pub sha256: [u8; 32],
}

/// One language with a dictionary.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Language {
    /// BCP-47 tag the windows use.
    pub id: &'static str,
    /// Folder at the source (`/dictionaries/<folder>/`).
    pub folder: &'static str,
    /// License of the dictionary (SPDX expression).
    pub license: &'static str,
    pub aff: Pin,
    pub dic: Pin,
}

impl Language {
    /// Bytes of the download.
    #[must_use]
    pub const fn bytes(&self) -> u64 {
        self.aff.bytes + self.dic.bytes
    }

    /// Install unit (id + store folder = the tag). `None`: a bad pin (a bug).
    #[must_use]
    pub fn unit(&self) -> Option<Unit> {
        let asset = |name: &str, pin: Pin| {
            Asset::new(
                SOURCE,
                format!(
                    "/wooorm/dictionaries/{COMMIT}/dictionaries/{}/{name}",
                    self.folder
                ),
                name,
                pin.bytes,
                pin.sha256,
            )
            .map(|asset| asset.with_revision(COMMIT))
            .ok()
        };
        Unit::new(
            self.id,
            self.id,
            vec![asset(AFF, self.aff)?, asset(DIC, self.dic)?],
        )
        .ok()
    }
}

