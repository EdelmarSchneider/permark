"""Writes `src/bpe/unicode_tables.rs`: the general categories the encodings' splitting rules ask about.

    python -m pip install unicodedata2
    python tools/unicode_tables.py > src/bpe/unicode_tables.rs && cargo fmt -p permark-plugin-token-count

Run it from the plugin crate folder. The tables follow the Unicode version of `unicodedata2` (printed in the header);
a character assigned in a newer version than the reference tokenizer's regex engine knows may split differently.
"""

import sys

import unicodedata2 as ud

# order = the code the Rust side reads
CATEGORIES = ["Lu", "Ll", "Lt", "Lm", "Lo", "M", "N"]


def code_of(c):
    cat = ud.category(c)
    if cat in ("Mn", "Mc", "Me"):
        return 6
    if cat in ("Nd", "Nl", "No"):
        return 7
    if cat in CATEGORIES:
        return CATEGORIES.index(cat) + 1
    return 0


def main():
    ranges = []
    start = None
    current = 0
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            code = 0
        else:
            code = code_of(chr(cp))
        if code != current:
            if current != 0:
                ranges.append((start, cp - 1, current))
            start = cp
            current = code
    if current != 0:
        ranges.append((start, 0x10FFFF, current))
    out = sys.stdout
    out.write("//! General categories for the splitting rules (generated by `tools/unicode_tables.py`; do not edit).\n")
    out.write(f"//! Unicode {ud.unidata_version}. Codes: 1 Lu, 2 Ll, 3 Lt, 4 Lm, 5 Lo, 6 M (Mn | Mc | Me), 7 N (Nd | Nl | No).\n\n")
    out.write(f"pub(super) static RANGES: [(u32, u32, u8); {len(ranges)}] = [\n")
    for a, b, code in ranges:
        out.write(f"    (0x{a:X}, 0x{b:X}, {code}),\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
