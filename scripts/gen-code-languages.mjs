// Regenerates src/lib/code/languageData.ts, the table of the languages highlight.js ships (id, display name, aliases).
//
// The table lets the app resolve a fence's language ("py", "c#", "ps1") without loading any grammar: only the grammar that is
// needed is imported, when a code block asks for it. A unit test compares the table with the installed highlight.js, so a
// dependency update that adds or renames a language fails it until this script is run again:
//
//   node scripts/gen-code-languages.mjs && npx prettier --write src/lib/code/languageData.ts

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import hljs from "highlight.js";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "lib", "code", "languageData.ts");

const rows = hljs
  .listLanguages()
  .sort()
  .map((id) => {
    const language = hljs.getLanguage(id);
    return [id, language?.name ?? id, language?.aliases ?? []];
  });

const lines = rows.map(
  ([id, name, aliases]) =>
    `  [${JSON.stringify(id)}, ${JSON.stringify(name)}, ${JSON.stringify(aliases)}],`,
);

writeFileSync(
  out,
  `// Generated by scripts/gen-code-languages.mjs from highlight.js ${hljs.versionString}. Do not edit by hand.

/** Every language highlight.js ships: its id (the name of its grammar), its display name and the aliases it answers to. */
export const HLJS_LANGUAGES: readonly (readonly [id: string, name: string, aliases: readonly string[]])[] = [
${lines.join("\n")}
];
`,
);
console.log(`${rows.length} languages written to ${out}`);
